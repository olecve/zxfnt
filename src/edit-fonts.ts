// Reads and writes glyphs for the glyph editor (docs/adr/0005-glyph-editor.md). A save goes through the same parser and
// writer as the build, and the fonts must still read without errors after it.

import { readdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { composeAll, COMPOSED_FILE } from "./compose.ts";
import type { EditorFile, EditorFont, EditorGlyph, SaveRequest } from "./editor/api.ts";
import { fontDirs, parseGlyphs, parseHeader, readGlyphFont, readIncluded, setGlyph, type Glyph } from "./glyphs.ts";

const HEADER_FILE = "font.txt";
// Importers and the compose step start their files with this line. The editor does not change these files.
const GENERATED = "# Generated by";

const rowText = (rows: boolean[][]) => rows.map((row) => row.map((p) => (p ? "X" : ".")).join(""));

async function readText(path: string): Promise<string | undefined> {
  return readFile(path, "utf8").catch(() => undefined);
}

export async function editorFonts(): Promise<EditorFont[]> {
  const fonts: EditorFont[] = [];
  for (const dir of await fontDirs()) {
    const header = parseHeader({ path: join(dir, HEADER_FILE), text: await readFile(join(dir, HEADER_FILE), "utf8") });
    const files: EditorFile[] = [];
    const byCodePoint = new Map<number, EditorGlyph>();
    const add = (path: string, glyphs: Glyph[]) => {
      for (const g of glyphs)
        byCodePoint.set(g.codePoint, { codePoint: g.codePoint, rows: rowText(g.rows), file: path });
    };
    for (const include of header.include) {
      const path = join(dir, include);
      add(path, (await readIncluded(path, header)).glyphs);
      files.push({ path, writable: false, included: true });
    }
    const names = (await readdir(dir)).filter((name) => name.endsWith(".txt") && name !== HEADER_FILE).sort();
    for (const name of names) {
      const path = join(dir, name);
      const text = await readFile(path, "utf8");
      add(path, parseGlyphs({ path, text }, header.width, header.height));
      files.push({ path, writable: !text.startsWith(GENERATED), included: false });
    }
    const glyphs = [...byCodePoint.values()].sort((a, b) => a.codePoint - b.codePoint);
    fonts.push({ ...header, dir, files, glyphs });
  }
  return fonts;
}

/** Writes one glyph into a file of its font, checks that every font still reads, and composes again. */
export async function saveGlyph(request: SaveRequest): Promise<void> {
  const font = (await editorFonts()).find((f) => f.name === request.font);
  if (!font) throw new Error(`no font "${request.font}"`);
  if (!/^[a-z0-9-]+\.txt$/.test(request.file) || request.file === HEADER_FILE || request.file === COMPOSED_FILE) {
    throw new Error(`"${request.file}" is not a glyph file name`);
  }
  const row = new RegExp(`^[X.]{${font.width}}$`);
  if (request.rows.length !== font.height || !request.rows.every((r) => row.test(r))) {
    throw new Error(`a glyph of ${font.name} has ${font.height} rows of ${font.width} "X" and "."`);
  }
  const path = join(font.dir, basename(request.file));
  const old = await readText(path);
  if (old?.startsWith(GENERATED)) throw new Error(`${path} is generated, so the editor does not change it`);

  const glyph = { codePoint: request.codePoint, rows: request.rows.map((r) => [...r].map((c) => c === "X")) };
  await writeFile(path, setGlyph(old ?? "", glyph));
  try {
    // Reading every font also checks that the code point is a character. composed.txt is made again below, and may
    // still have this glyph.
    for (const dir of await fontDirs()) await readGlyphFont(dir, [COMPOSED_FILE]);
  } catch (error) {
    if (old === undefined) await rm(path);
    else await writeFile(path, old);
    throw error;
  }
  await composeAll();
}
