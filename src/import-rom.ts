// Usage: npm run import:rom -- <48.rom or 768-byte font> [output, default fonts/zx-rom/rom.txt]

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fontBytes, glyphText } from "./rom.ts";

const [input, output = "fonts/zx-rom/rom.txt"] = process.argv.slice(2);
if (!input) {
  console.error("usage: npm run import:rom -- <file> [output]");
  process.exit(1);
}

const file = await readFile(input);
const sha1 = createHash("sha1").update(file).digest("hex");
const comment = [
  `Generated by "npm run import:rom" from ${basename(input)} (${file.length} bytes, SHA-1 ${sha1}).`,
  "Do not edit: import again instead. Put new glyphs in another file.",
].join("\n");
await writeFile(output, glyphText(fontBytes(file), comment));
console.log(`${input} -> ${output}`);
